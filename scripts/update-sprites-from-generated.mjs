#!/usr/bin/env node
/**
 * Replace SVG placeholder sprites with real pixel art PNGs.
 * Reads from client/assets/generated/ and updates client/src/sprites.ts
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT = join(__dirname, '..');
const GENERATED = join(PROJECT, 'client/assets/generated');
const SPRITES_TS = join(PROJECT, 'client/src/sprites.ts');

// Mapping: sprite key → generated PNG path (use the smaller game-size versions)
const SPRITE_MAP = {
  // Floor tiles (64x32)
  'floor_stone': 'tiles/floor_stone_64x32.png',
  'floor_wood': 'tiles/floor_wood_64x32.png',
  'floor_grass': 'tiles/floor_grass_64x32.png',
  'floor_carpet': 'tiles/floor_carpet_64x32.png',

  // Walls (64x128)
  'wall_brick': 'walls/wall_brick_64x128.png',
  'wall_wood': 'walls/wall_wood_64x128.png',

  // Door
  'door': 'furniture/door_96x192.png',

  // Agent sprites (64x128)
  'agent_dir0': 'characters/agent_idle_se_64x128.png',  // SE = dir0
  'agent_dir2': 'characters/agent_idle_se_64x128.png',  // Reuse SE for now
  'agent_dir4': 'characters/agent_idle_sw_64x128.png',  // SW = dir4
  'agent_dir6': 'characters/agent_idle_sw_64x128.png',  // Reuse SW for now

  // Furniture
  'furn_chair': 'furniture/chair_wood_48x64.png',
  'furn_table': 'furniture/table_wood_64x48.png',
  'furn_lamp': 'furniture/lamp_32x96.png',
  'furn_sofa': 'furniture/sofa_blue_64x48.png',
  'furn_plant': 'furniture/plant_32x48.png',
  'furn_bookshelf': 'furniture/bookshelf_48x96.png',
  'furn_computer': 'furniture/computer_64x64.png',
  'furn_bed': 'furniture/bed_96x64.png',
  'furn_fridge': 'furniture/fridge_48x64.png',
  'furn_tv': 'furniture/tv_retro_64x64.png',
};

let updated = 0;
let skipped = 0;

// Read current sprites.ts
let content = readFileSync(SPRITES_TS, 'utf-8');

for (const [key, relPath] of Object.entries(SPRITE_MAP)) {
  const fullPath = join(GENERATED, relPath);
  
  if (!existsSync(fullPath)) {
    console.log(`⏭️  ${key}: ${relPath} not found, keeping SVG`);
    skipped++;
    continue;
  }

  const pngData = readFileSync(fullPath);
  const base64 = pngData.toString('base64');
  const dataUri = `data:image/png;base64,${base64}`;

  // Replace the data URI in sprites.ts
  const regex = new RegExp(`'${key}':\\s*'data:[^']*'`);
  if (regex.test(content)) {
    content = content.replace(regex, `'${key}': '${dataUri}'`);
    console.log(`✅ ${key}: replaced with ${relPath} (${Math.round(base64.length / 1024)}KB)`);
    updated++;
  } else {
    console.log(`⚠️  ${key}: pattern not found in sprites.ts`);
    skipped++;
  }
}

// Update the header comment
content = content.replace(
  '// Auto-generated sprite atlas — do not edit\n// Generated by scripts/generate-sprites.mjs',
  '// Sprite atlas with real pixel art assets\n// Updated by scripts/update-sprites-from-generated.mjs\n// Original SVG placeholders replaced with Gemini-generated pixel art PNGs'
);

writeFileSync(SPRITES_TS, content);
console.log(`\n📊 Done: ${updated} replaced, ${skipped} skipped`);
